// Nexus Techstore — Route Plan
// Method | Path                  | Purpose
// -----------------------------------------------------------------
// GET    | /category             | Display all categories.

// GET    | /category/:id         | Display a specific category and its items.
// GET    | /category/new         | Display the form to create a category.
// POST   | /category/new         | Create a new category.
// GET    | /category/:id/update  | Display the form to update a category.
// POST   | /category/:id/update  | Update an existing category.
// POST   | /category/:id/delete  | Delete a category, provided it contains no items.
// GET    | /item                 | Display all items.
// GET    | /item/:id             | Display a specific item's details.
// GET    | /item/new             | Display the form to create an item.
// POST   | /item/new             | Create a new item.
// GET    | /item/:id/update      | Display the form to update an item.
// POST   | /item/:id/update      | Update an existing item.
// POST   | /item/:id/delete      | Delete an item.
